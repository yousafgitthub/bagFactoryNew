function billToPurchaseOrder(b: PurchaseBill): PurchaseOrder {
  const purchaseCategory = billCategoryToPurchaseCategory(b.category);
  const invCat = mapLegacyBillCategory(b.category);
  const qty = b.quantityKg;
  return {
    id: b.id,
    purchaseNumber: b.purchaseNumber,
    purchaseDate: b.purchaseDate,
    supplierId: b.supplierId,
    supplierName: b.supplierName,
    supplierInvoiceNumber: b.documentRef,
    purchaseCategory,
    warehouse: b.warehouse,
    paymentDueDate: b.dueDate,
    notes: b.notes,
    items: [
      {
        id: `${b.id}-line-1`,
        itemName: b.materialName,
        inventoryCategory: invCat,
        orderedQty: qty,
        receivedQty: qty,
        ratePerUnit: b.ratePerKg,
        unit: 'kg',
        lineTotal: b.totalAmount,
      },
    ],
    subtotal: b.totalAmount,
    discount: 0,
    discountType: 'Fixed',
    additionalCharges: 0,
    taxAmount: 0,
    netTotal: b.totalAmount,
    amountPaid: b.paidAmount,
    remainingPayable: b.remainingPayable,
    documentStatus: 'Received',
    paymentStatus: computePurchasePaymentStatus(b.totalAmount, b.paidAmount, b.dueDate),
    attachments: b.documentRef
      ? [
          {
            id: `att-${b.id}`,
            fileName: b.documentRef,
            fileSize: '240 KB',
            label: 'Supplier invoice',
            uploadDate: b.purchaseDate,
            previewNote: 'Mock preview — permanent storage connects at backend integration.',
          },
        ]
      : [],
  };
}

